/** English texts of the publish problems of src/lib/studio/shared.ts, by code. */
const PROBLEM_EN: Record<string, (page: number) => string> = {
  language: () =>
    "The book is not in Hebrew yet. The public library is in Hebrew and Arabic only: translate the book and approve the translation before submitting.",
  translator: () => "The translator's name is missing (in the book details tab)",
  title: () => "The book has no title",
  summary: () => "The book has no summary",
  author: () => "The author's name is missing",
  license: () => "The license is missing (for example: All rights reserved, or CC BY 4.0)",
  categories: () => "Choose at least one category",
  pages: () => "The book has no pages",
  "blank-page": (page) => `Page ${page} is empty`,
  "nikud-mismatch": (page) => `On page ${page} the vocalized text has a different number of words than the plain text`,
  "narration-stale": (page) =>
    `On page ${page} the text changed after the narration. Narrate the page again or remove the narration.`,
  "no-text": () => "No page has any text",
};

/** A publish problem in the interface language; Hebrew keeps the message as computed. */
export function publishProblemText(locale: Locale, problem: PublishProblem): string {
  if (locale === "he") return problem.message;
  const english = PROBLEM_EN[problem.code];
  return english ? english((problem.pageIndex ?? 0) + 1) : problem.message;
}

