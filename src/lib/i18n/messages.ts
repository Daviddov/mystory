export type TaxonomyKind = keyof typeof TAXONOMY_EN;

/**
 * Label (or description) of a taxonomy item in the interface language. `item`
 * is the Hebrew item from src/lib/taxonomy.ts; unknown slugs keep it.
 */
export function taxonomyText(
  locale: Locale,
  kind: TaxonomyKind,
  slug: string,
  item: { label: string; description?: string },
): { label: string; description?: string } {
  if (locale === "he") return item;
  const english = (TAXONOMY_EN[kind] as Record<string, EnglishName>)[slug];
  return english ? { label: english.label, description: english.description ?? item.description } : item;
}
