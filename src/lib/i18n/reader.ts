const CREDIT_LABELS_EN: Record<string, string> = {
  author: "Written by",
  illustrator: "Illustrated by",
  designer: "Designed by",
  editor: "Edited by",
  creators: "Created by",
  originalTitle: "Original title",
};

/**
 * Label of a credit line from creditPeople() (src/lib/credits.ts keeps its
 * Hebrew labels for the PDF) in the interface language.
 */
export function creditLabel(locale: Locale, line: CreditLine, bookLanguage: BookLanguage = "he"): string {
  if (locale === "he") return line.label;
  if (line.key === "translator") return bookLanguage === "he" ? "Hebrew translation" : "Translation";
  if (line.key.startsWith("translator-")) {
    const language = line.key.slice("translator-".length) as BookLanguage;
    return LANGUAGE_IN_EN[language] ? `${LANGUAGE_IN_EN[language]} translation` : "Translation";
  }
  return CREDIT_LABELS_EN[line.key] ?? line.label;
}
