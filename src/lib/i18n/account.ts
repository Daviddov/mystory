/** quotaMessage() of src/lib/generation/quota.ts in the interface language. */
export function quotaText(
  locale: Locale,
  state: { blocked?: "weekly" | "attempts" | "active"; limit: number; used: number },
): string {
  const t = ACCOUNT_MESSAGES[locale].createPage.quota;
  switch (state.blocked) {
    case "active":
      return t.active;
    case "weekly":
      return state.limit === 0 ? t.closed : state.limit === 1 ? t.weeklyOne : t.weekly(state.limit, state.used);
    case "attempts":
      return t.attempts;
    default:
      return "";
  }
}
